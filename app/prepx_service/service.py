from pathlib import PurePosixPath

from sqlalchemy import text
from sqlalchemy.orm import Session

from .config import Settings
from .errors import ServiceError
from .llm import GroqClient
from app.models import Exam, Option, PdfUpload, Question, User
from .ocr import LocalOCR
from .pdf import read_pdf
from .schemas import BatchResult, DocumentResult, QuestionResult


def relative_levels(scores: list[float]) -> list[str]:
    """Midrank percentiles keep identical estimates in the same band."""
    n = len(scores)
    result = []
    for score in scores:
        percentile = (sum(v < score for v in scores) + .5 * sum(v == score for v in scores)) / n
        result.append('easy' if percentile < 1 / 3 else 'difficult' if percentile > 2 / 3 else 'medium')
    return result


class IngestionService:
    def __init__(self, settings: Settings, llm=None, ocr=None):
        self.settings = settings
        self.llm = llm or GroqClient(settings)
        self.ocr = ocr or LocalOCR(settings)

    def ingest(self, session: Session, uploads: list[tuple[str, bytes]], user_id: int,
               exam_id: int | None = None, examname: str | None = None,
               languages: list[str] | None = None, backend='tesseract', force_ocr=False) -> BatchResult:
        if session.get(User, user_id) is None:
            raise ServiceError('User does not exist; create the user in PrepX first.', 404)
        existing = session.get(Exam, exam_id) if exam_id else None
        if exam_id and (not existing or existing.user_id != user_id):
            raise ServiceError('Exam does not exist for this user.', 404)
        existing_title = existing.title if existing else None
        session.rollback()
        prepared = []
        # All extraction and answer generation happens before any database mutation.
        for filename, data in uploads:
            filename = PurePosixPath(filename.replace('\\', '/')).name[:255]
            source = read_pdf(filename, data, self.settings, self.ocr, languages, backend, force_ocr)
            extracted = self.llm.extract(source.prompt_text(), languages)
            for q in extracted.questions:
                if any(p < 1 or p > len(source.pages) for p in q.source_pages):
                    raise ServiceError('Extraction returned an invalid source page.', 502)
                q.source_pages = sorted(set(q.source_pages))
            provenance = ['pdf' if q.correct_labels else 'unresolved' for q in extracted.questions]
            missing = [i for i, q in enumerate(extracted.questions) if not q.correct_labels]
            for start in range(0, len(missing), 15):
                indices = missing[start:start + 15]
                payload = [dict(question_index=i, question_text=extracted.questions[i].question_text,
                                options=[o.model_dump() for o in extracted.questions[i].options]) for i in indices]
                batch = self.llm.answer(payload)
                if len(batch.answers) != len(indices) or {a.question_index for a in batch.answers} != set(indices):
                    raise ServiceError('Groq omitted or duplicated answers; nothing was saved.', 502)
                for answer in batch.answers:
                    q = extracted.questions[answer.question_index]
                    labels = {o.label for o in q.options}
                    if len(set(answer.correct_labels)) != len(answer.correct_labels) or not set(answer.correct_labels) <= labels:
                        raise ServiceError('Groq returned an answer outside the available options.', 502)
                    q.correct_labels = answer.correct_labels
                    if answer.warning:
                        q.warnings.append(answer.warning)
                    if answer.correct_labels:
                        provenance[answer.question_index] = 'groq'
                        q.warnings.append('Answer generated by Groq; not an official answer key.')
                    else:
                        q.warnings.append('No reliable answer available; is_correct is null for all options.')
            title = (existing_title or examname or extracted.examname or filename.rsplit('.', 1)[0])[:255]
            levels = relative_levels([q.difficulty_score for q in extracted.questions])
            prepared.append((source, extracted, provenance, levels, title))

        documents = []
        try:
            # Use the same SQLite serialization convention as exam conduction, only for writes.
            session.execute(text('BEGIN IMMEDIATE'))
            if session.get(User, user_id) is None:
                raise ServiceError('User no longer exists.', 404)
            existing = session.get(Exam, exam_id) if exam_id else None
            if exam_id and (not existing or existing.user_id != user_id):
                raise ServiceError('Exam does not exist for this user.', 404)
            for source, extracted, provenance, levels, title in prepared:
                upload = PdfUpload(original_filename=source.filename, user_id=user_id)
                session.add(upload)
                session.flush()
                exam = existing or Exam(title=title, user_id=user_id, pdf_upload_id=upload.id)
                if not existing:
                    session.add(exam)
                    session.flush()
                results = []
                for q, answer_source, level in zip(extracted.questions, provenance, levels):
                    # Page-level provenance; this does not assert the question contains a diagram.
                    has_image = any(source.pages[p - 1].has_image for p in q.source_pages)
                    question = Question(question_text=q.question_text, topic=q.topic, difficulty=level,
                                        has_image=has_image, pdf_upload_id=upload.id)
                    question.options = [Option(label=o.label, text=o.text,
                                              is_correct=(o.label in q.correct_labels) if q.correct_labels else None)
                                        for o in q.options]
                    exam.questions.append(question)
                    session.add(question)
                    session.flush()
                    results.append(QuestionResult(**q.model_dump(), question_id=question.id, level=level,
                        examname=title, answer_source=answer_source, has_image=has_image,
                        correct_answer_text='; '.join(o.text for o in q.options if o.label in q.correct_labels) or None))
                exam.question_count = len(exam.questions)
                exam.important_topics = ', '.join(sorted({q.topic for q in exam.questions if q.topic}))
                documents.append(DocumentResult(filename=source.filename, pdf_upload_id=upload.id, exam_id=exam.id,
                    pages=len(source.pages), warnings=source.warnings, questions=results))
            response = BatchResult(documents=documents)
            session.commit()
            return response
        except Exception:
            session.rollback()
            raise
